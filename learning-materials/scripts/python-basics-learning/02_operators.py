# ⚠️ 坑（超级经典）：用乘法初始化“嵌套列表”时，内层被所有行共享同一个引用！
grid_bad = [[0] * 3] * 2      # 先造内层列表，再把它的“引用”重复 2 次
grid_bad[0][0] = 99
print(f"grid_bad = {grid_bad}  # 改一格两行都变，因为 is 判定为 {grid_bad[0] is grid_bad[1]}")
grid_ok = [[0] * 3 for _ in range(2)]   # 正确：每行单独创建
grid_ok[0][0] = 99
print(f"grid_ok  = {grid_ok}   # 只有第一行变，is 判定为 {grid_ok[0] is grid_ok[1]}")
# 顺带：重复 0 次或负数次会得到空序列，不报错。
print(f"'ab' * 0 = {'ab' * 0!r} | [1, 2] * -1 = {[1, 2] * -1}")
