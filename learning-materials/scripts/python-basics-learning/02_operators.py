# 6. 位运算符 & | ^ ~ << >>：直接操作二进制
# ============================================================
n = 6
print(f"n = {n}，bin(6) = {bin(n)} | bin(10) = {bin(10)} | bin(3) = {bin(3)}")
p, q = 6, 3   # 0b110 和 0b011
print(f"6 & 3 = {p & q}（都是1才得1）| 6 | 3 = {p | q}（有1就得1）| 6 ^ 3 = {p ^ q}（不同得1）")
print(f"~6 = {~p}（~x == -(x+1)）| 6 << 1 = {p << 1}（×2）| 6 << 2 = {p << 2}（×4）"
      f"| 6 >> 1 = {p >> 1}（÷2）")
# ⚠️ 坑：`&` 不等于 `and`！
print(f"6 & 3 = {6 & 3}（按位）| 6 and 3 = {6 and 3}（逻辑，返回最后一个真值）")

# 实战：用位做“权限/标志位”，一个整数装下所有权限。
READ, WRITE, EXEC = 1, 2, 4   # 0b001, 0b010, 0b100
perm = READ | WRITE
print(f"perm = READ | WRITE = {perm}（{bin(perm)}）")
print(f"有读权限？ {bool(perm & READ)} | 有执行权限？ {bool(perm & EXEC)}")
perm |= EXEC
print(f"加执行权限后 perm = {perm}（{bin(perm)}）")
perm &= ~WRITE
print(f"去掉写权限后 perm = {perm}（{bin(perm)}）")

# 异或技巧 1：不用临时变量交换两个数。
u, v = 5, 9
print(f"交换前 u = {u}, v = {v}")
u = u ^ v
v = u ^ v
u = u ^ v
print(f"异或交换后 u = {u}, v = {v}（Python 里更推荐 u, v = v, u）")
# 异或技巧 2：一堆“成对出现”的数里找出唯一单身的那个（a ^ a == 0）。
nums = [4, 1, 2, 1, 2]
res = 0
for item in nums:
    res ^= item
print(f"nums = {nums} 全部异或 -> {res}   # 其他的成对抵消了")
