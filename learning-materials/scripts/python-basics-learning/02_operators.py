# 9. 增强赋值运算符：+= -= *= //= **= &= |= ^= <<= ...
# ============================================================
num = 10
num += 5
num -= 3
num *= 2
num //= 5
num **= 2
print(f"10 -> +=5 -> -=3 -> *=2 -> //=5 -> **=2 得 {num}")
bits = 0b1010
bits &= 0b1100
print(f"0b1010 &= 0b1100 -> {bits}（{bin(bits)}）")
bits = 0b1010
bits |= 0b0101
print(f"0b1010 |= 0b0101 -> {bits}（{bin(bits)}）")
# ⚠️ 坑 1：列表 `+=` 是“原地扩展”，id 不变；`lst = lst + [...]` 会新建列表，id 变。
L = [1, 2]
bid = id(L)
L += [3]
print(f"L += [3] -> {L}，id 变了吗？{bid != id(L)}（False = 原地改）")
M = [1, 2]
bid = id(M)
M = M + [3]
print(f"M = M + [3] -> {M}，id 变了吗？{bid != id(M)}（True = 新对象）")
shared = [1, 2, 3]
alias = shared
alias += [4]
print(f"shared = {shared}   # 别名原地改动，本体也跟着变")
# ⚠️ 坑 2：元组里的可变元素用 += 会先原地改、再因“给元组下标赋值”而报 TypeError。
tup = ([1], 2)
try:
    tup[0] += [9]
except TypeError as e:
    print(f"tup[0] += [9] 报错：{type(e).__name__}: {e}")
print(f"但列表其实已经被改了：tup = {tup}   # 著名的历史坑")
# ⚠️ 坑 3：字符串不可变，循环里 s += x 每次都新建整串，性能很差；先收集再 join。
parts = []
for w in ["Py", "thon", " 真", "好用"]:
    parts.append(w)
print(f"用 join 拼接 -> {''.join(parts)!r}（循环里拼字符串请先收集再 join）")
