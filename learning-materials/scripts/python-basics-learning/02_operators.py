# 2. 字符串与序列的 + 和 *：拼接与重复
# ============================================================
# 同一个 + 号作用在不同类型上含义不同，这叫“运算符重载”。
print(f"'ab' + 'cd' = {'ab' + 'cd'} | 'ab' * 3 = {'ab' * 3} | '=' * 20 -> {'=' * 20}")
print(f"[0] * 5 = {[0] * 5}    # 初始化定长列表的常用写法")
