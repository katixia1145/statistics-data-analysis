# ============================================================
# 1. 算术运算符：+ - * / // % **
# ============================================================
# 记住一句话：Python 的 `/` 是“真除法”，结果永远是 float。这样设计就是为了避开
# 老语言（C/Java）里 `1/2 == 0` 那种把新手坑哭的行为。
a, b = 7, 2
print(f"a = {a}, b = {b}")
print(f"a + b = {a + b} | a - b = {a - b} | a * b = {a * b}")
print(f"a / b = {a / b}  # 真除法，一定返回 float")
print(f"a // b = {a // b} | a % b = {a % b} | a ** b = {a ** b}")
# ⚠️ 坑：a / b 即使能整除，结果也是 float 不是 int。
print(f"4 / 2 = {4 / 2}（类型 {type(4 / 2).__name__}，不是 2）| 3 + 0.5 = {3 + 0.5}")
print(f"7 // 2 = {7 // 2} | 7 % 2 = {7 % 2} | -7 // 2 = {-7 // 2}（-3.5 向下取整得 -4）")
# (1) `//` 是“向下取整”(floor，往数轴左边走)，不是“截断小数”(trunc，往 0 靠)；负数时两者才分家。
# 为什么是 -4？floor(-3.5) = 不超过 -3.5 的最大整数 = -4。Python 选 floor 是为了
# 让恒等式 (a//b)*b + a%b == a 对任意符号都成立：
print(f"(a//b)*b + a%b == a ? {(-7 // 2) * 2 + (-7 % 2) == -7}")

# (2) `%` 的结果符号永远跟着“除数”(右边那个数)走。
print(f"-7 % 3 = {-7 % 3} | 7 % -3 = {7 % -3} | -7 % -3 = {-7 % -3}")
# ⚠️ 坑：C / Java / JS 里 -7 % 3 == -1（符号跟被除数），Python 是 2（跟除数）。
#         从 C 转过来判奇偶时，别写 x % 2 == 1，写 x % 2 == 0 或 abs(x) % 2 更稳。

# (3) `**` 幂运算的常见玩法
print(f"2 ** 10 = {2 ** 10} | 9 ** 0.5 = {9 ** 0.5} | 5 ** -1 = {5 ** -1}")
# ⚠️ 坑：`**` 优先级高于一元负号，所以 -2 ** 2 是 -4 而不是 4。
print(f"-2 ** 2 = {-2 ** 2}（先幂后取负）| (-2) ** 2 = {(-2) ** 2}（想平方要加括号）")
