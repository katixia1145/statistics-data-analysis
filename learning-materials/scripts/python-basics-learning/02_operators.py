# 10. 海象运算符 := ：在表达式里赋值
# ============================================================
# 作用：先算出来、顺手起个名字，避免把同一个表达式写两遍。
data = iter([3, 1, 4, 1, 5])
total = 0
while (n := next(data, None)) is not None:   # 场景 A：while 里边读边判断
    total += n
print(f"while + 海象累加 = {total}   # 读到 None 就退出，不会死循环")

def heavy_calc():
    return 4 * 5

if (got := heavy_calc()) > 15:               # 场景 B：if 里先算再判断
    print(f"if + 海象：got = {got} > 15，进入分支")
# 场景 C：推导式里复用“过滤条件算出来的值”
values = [1, 2, 3, 4, 5, 6]
squares = [sq for it in values if (sq := it * it) > 4]
print(f"推导式 + 海象 -> {squares}（只剩平方大于 4 的）")
# ⚠️ 坑：海象优先级很低，容易“粘错”，规范写法是永远加括号 (n := 10)。
#         而且不能写 `x = n := 5`（语法错误），必须 `x = (n := 5)`。
print("-" * 60)

