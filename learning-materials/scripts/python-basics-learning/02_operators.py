# 5. 逻辑运算符 and / or / not：返回操作数本身！
# ============================================================
# 这是最让新手懵的一点：and / or 返回的不是 True/False，而是“决定结果的那个操作数”。
# 规则：and 从左往右找第一个假值，找到就返回它，否则返回最后一个；
#       or  从左往右找第一个真值，找到就返回它，否则返回最后一个。
# 假值：False, None, 0, 0.0, "", [], {}, set()
print(f"7 and 0 = {7 and 0} | 0 and 7 = {0 and 7} | 7 or 0 = {7 or 0}")
print(f"0 or 'default' = {0 or 'default'!r}   # 这就是“默认值”写法的来源")
user_name = ""
print(f"user_name or '匿名用户' -> {user_name or '匿名用户'!r}")
# ⚠️ 坑：or 会把 0 当成“空”，所以“0 是合法值”时不能用它兜底。
count = 0
print(f"count or 10 = {count or 10}（0 被换掉了！）| "
      f"count if count is not None else 10 = {count if count is not None else 10}")
print(f"not 0 -> {not 0} | not 'abc' -> {not 'abc'} | not [] -> {not []}")

# 短路求值：and / or 一旦能定结果，右边“根本不执行”。用一个会打印的函数抓现行：
def boom():
    print("  [boom() 被执行了！这行不该出现]")
    return True

def fail():
    print("  [fail() 被执行了]")
    return False

print(f"False and boom() -> {False and boom()}   # 没有 boom 输出 = 右边没跑")
print(f"True or boom() -> {True or boom()}      # 同样没跑")
print(f"fail() or '兜底' -> {fail() or '兜底'!r}   # 左边假，右边才求值")
# ⚠️ 坑：and / or 优先级低于比较运算符；not 也低于比较。
print(f"not 1 == 2 -> {not 1 == 2}   # 等价 not (1 == 2)")
print("-" * 60)

